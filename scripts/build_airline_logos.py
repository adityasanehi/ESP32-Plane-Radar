#!/usr/bin/env python3
"""Bundle airline logos into the firmware so frequent airlines need no download.

  python3 scripts/build_airline_logos.py IGO AIC SEJ ...   (airline ICAO codes)

For each airline, fetches the same pair of 34 px JPEGs the device would download
at runtime (FlightAware logo via the wsrv.nl proxy, composited on black and on
white), and writes src/data/airline_logos_data.cpp. Airlines without a logo are
skipped with a warning.
"""
import pathlib
import sys
import urllib.error
import urllib.request

URL = ("https://wsrv.nl/?url=cdn.jsdelivr.net/gh/Jxck-S/airline-logos@main/"
       "flightaware_logos/{icao}.png&w=34&h=34&fit=contain&bg={bg}&output=jpg&q=92")
OUT = pathlib.Path(__file__).resolve().parent.parent / "src/data/airline_logos_data.cpp"


def fetch(icao, bg):
    req = urllib.request.Request(URL.format(icao=icao, bg=bg),
                                 headers={"User-Agent": "plane-radar-build"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"const uint8_t {name}[] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def main(codes):
    arrays, rows, total = [], [], 0
    for icao in codes:
        try:
            black, white = fetch(icao, "black"), fetch(icao, "white")
        except urllib.error.HTTPError as e:
            print(f"skip {icao}: HTTP {e.code}", file=sys.stderr)
            continue
        arrays += [c_array(f"k{icao}Black", black), c_array(f"k{icao}White", white)]
        rows.append(f'    {{"{icao}", k{icao}Black, sizeof(k{icao}Black), '
                    f"k{icao}White, sizeof(k{icao}White)}},")
        total += len(black) + len(white)
        print(f"{icao}: {len(black)} + {len(white)} bytes")
    OUT.write_text(
        "// Generated by scripts/build_airline_logos.py -- do not edit.\n"
        "// Logos: FlightAware via github.com/Jxck-S/airline-logos; trademarks of\n"
        "// their respective airlines.\n\n"
        '#include "data/airline_logos.h"\n\nnamespace data {\n\nnamespace {\n\n'
        + "\n".join(arrays)
        + "\n}  // namespace\n\nconst BundledLogo kBundledLogos[] = {\n"
        + "\n".join(rows)
        + f"\n}};\nconst size_t kBundledLogoCount = {len(rows)};\n\n}}  // namespace data\n")
    print(f"{len(rows)} airlines, {total} bytes -> {OUT}")


if __name__ == "__main__":
    main([c.upper() for c in sys.argv[1:]])
